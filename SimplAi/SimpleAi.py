import math
import random

random.seed(6)  # фиксируем генератор случайных чисел, чтобы обучение было воспроизводимым.
# ВНИМАНИЕ: seed подобран так, чтобы оба скрытых нейрона «выжили». Это свойство ReLU
# (см. комментарий в simpleAi): при неудачном старте нейрон умирает и обучение
# застревает — тогда можно просто сменить seed. У tanh такой проблемы нет.

# ==========================================
# ВЕСА — случайная инициализация
# ==========================================
# ПОЧЕМУ случайная: если оба скрытых нейрона стартуют с одинаковыми весами,
# они навсегда останутся одинаковыми (симметрия) и сеть выродится в один нейрон,
# который XNOR выучить не может — задача нелинейная (её нельзя разделить прямой).
# Случайные веса «разбивают симметрию»: нейроны начинают обучаться по-разному
# и специализироваться каждый на своей части задачи.
h1x1, h1x2, h1b = random.uniform(-1, 1), random.uniform(-1, 1), random.uniform(-1, 1)  # скрытый нейрон 1
h2x1, h2x2, h2b = random.uniform(-1, 1), random.uniform(-1, 1), random.uniform(-1, 1)  # скрытый нейрон 2
h1o, h2o, b_out = random.uniform(-1, 1), random.uniform(-1, 1), random.uniform(-1, 1)  # выходной нейрон

# Параметры обучения
lr = 0.5     # скорость обучения: насколько сильно меняем веса за один шаг
# при seed(6) псевдослучайного генератора и пр. параметрах обучения
# нейросеть не ошибается уже при EPOCHS = 73. Для более точного обучения поставлено значение выше
EPOCHS = 1000  # сколько раз пройдём по всему набору данных (с ReLU сходится чуть дольше, чем с tanh)

# Данные для обучения XNOR: [x1, x2] -> target (одинаковые входы дают 1, разные — 0)
X = [(0, 0), (0, 1), (1, 0), (1, 1)]
Y = [1.0, 0.0, 0.0, 1.0]

# ==========================================
# Сама нейросеть на 4х нейрона на весах определенных выше
# ==========================================
def simpleAi(x1, x2):
    # Скрытый слой: сумма весов * входы + сдвиг, затем активация ReLU.
    # ReLU — самая простая нелинейность: оставляет число как есть, если оно
    # положительное, иначе обнуляет (max(0, z)). Без неё сеть была бы
    # линейной и не смогла бы решить XNOR.
    # Классический выбор — tanh (сжимает сигнал в (-1, 1)): он «мягче»
    # и даёт ненулевой градиент почти всегда, поэтому обучение чуть быстрее
    # и стабильнее. Здесь взят ReLU ради простоты — математики в коде меньше,
    # а точность для такой маленькой задачи почти не страдает.
    h1 = max(0.0, h1x1 * x1 + h1x2 * x2 + h1b) # НЕЙРОН 1 (скрытый)
    h2 = max(0.0, h2x1 * x1 + h2x2 * x2 + h2b) # НЕЙРОН 2 (скрытый)
    # Выходной слой: та же схема, но сигмоид сжимает результат в (0, 1) —
    # это удобно, ответ читается как вероятность принадлежности к классу 1.
    # НЕЙРОН 3: z_out (взвешивание) и y_pred (активация)
    z_out = h1o * h1 + h2o * h2 + b_out
    y_pred = 1.0 / (1.0 + math.exp(-z_out))
    return h1, h2, z_out, y_pred

# ==========================================
# ОБУЧЕНИЕ: батч из 4 примеров -> один шаг обновления весов
# ==========================================
# Идея: для каждого веса считаем, КУДА ошибка «толкает» сеть (градиент),
# и сдвигаем вес на маленький шаг в ПРОТИВОПОЛОЖНУЮ сторону — вниз по ошибке.
# Это и есть градиентный спуск.
for epoch in range(EPOCHS):
    total_loss = 0.0
    # Накапливаем градиенты всех весов по 4 примерам
    gh1x1 = gh1x2 = gh1b = gh2x1 = gh2x2 = gh2b = gh1o = gh2o = gb_out = 0.0

    for i in range(4):
        x1, x2 = X[i]
        target = Y[i]

        # 1) Прямой проход — ответ сети
        h1, h2, z_out, y_pred = simpleAi(x1, x2)

        # 2) Ошибка сети = квадрат разницы между ответом и ожиданием (MSE)
        error = y_pred - target
        total_loss += error ** 2

        # 3) Обратный проход — правило цепочки: раскручиваем ошибку
        #    от выхода назад через производные каждого звена.
        # На выходе: производная ошибки (2 * error) умножается
        # на производную сигмоиды (y * (1 - y)).
        dl_dz_out = (2 * error) * (y_pred * (1 - y_pred))

        # Выходной слой: вес h1o влияет на ошибку через сигнал h1
        gh1o += dl_dz_out * h1
        gh2o += dl_dz_out * h2
        gb_out += dl_dz_out

        # Скрытый слой 1: производная ReLU простая — 1, если нейрон
        # «живой» (h > 0), иначе 0 (мёртвый нейрон не обучается).
        dl_dh1 = dl_dz_out * h1o
        dl_dz1 = dl_dh1 * (1.0 if h1 > 0 else 0.0)
        gh1x1 += dl_dz1 * x1
        gh1x2 += dl_dz1 * x2
        gh1b += dl_dz1

        # Скрытый слой 2: аналогично
        dl_dh2 = dl_dz_out * h2o
        dl_dz2 = dl_dh2 * (1.0 if h2 > 0 else 0.0)
        gh2x1 += dl_dz2 * x1
        gh2x2 += dl_dz2 * x2
        gh2b += dl_dz2

    # 4) Обновление весов: градиент усредняем по 4 примерам и делаем шаг
    #    против градиента (-lr * g). Один шаг на эпоху = один проход по всем данным.
    n = 4
    h1x1 -= lr * (gh1x1 / n)
    h1x2 -= lr * (gh1x2 / n)
    h1b -= lr * (gh1b / n)
    h2x1 -= lr * (gh2x1 / n)
    h2x2 -= lr * (gh2x2 / n)
    h2b -= lr * (gh2b / n)
    h1o -= lr * (gh1o / n)
    h2o -= lr * (gh2o / n)
    b_out -= lr * (gb_out / n)

    # Печатаем прогресс раз в 100 эпох
    if (epoch + 1) % 100 == 0:
        print(f"N={epoch + 1:4d} | Loss: {total_loss / n:.4f} | "
              f"h1=[{h1x1:+.2f},{h1x2:+.2f},{h1b:+.2f}] h2=[{h2x1:+.2f},{h2x2:+.2f},{h2b:+.2f}] "
              f"выход=[{h1o:+.2f},{h2o:+.2f},{b_out:+.2f}]")

# ==========================================
# ПРОВЕРКА: как сеть отвечает после обучения
# ==========================================
print()
print("**********************************************")
print("     Проверим как получилось обучение")
print("**********************************************")
all_ok = True
for i in range(4):
    x1, x2 = X[i]
    target = Y[i]
    h1, h2, z_out, y_pred = simpleAi(x1, x2)
    # Порог 0.5: ответ >= 0.5 считаем 1, иначе 0
    pred = 1 if y_pred >= 0.5 else 0
    ok = (pred == target)
    all_ok = all_ok and ok
    print(f"Вход: {x1},{x2} | ожидание: {int(target)} | ответ сети: {y_pred:.3f} -> {pred} "
          f"| скрытые: {h1:.3f},{h2:.3f} | {'ВЕРНО' if ok else 'ОШИБКА'}")
print()
print("ИТОГ: XNOR выучен!" if all_ok else "ИТОГ: сеть ошибается — увеличим число эпох или изменим скорость обучения")